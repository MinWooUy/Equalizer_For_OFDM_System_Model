function X = map_ofdm_subcarriers( ...
    dataSymbols, pilotPattern, dataIndices, pilotIndices, NFFT)
%MAP_OFDM_SUBCARRIERS Ánh xạ data, pilot và null lên lưới OFDM.
%   X sử dụng thứ tự FFT gốc của MATLAB: DC nằm tại phần tử đầu tiên.
%   Mỗi cột của X là một symbol OFDM trong miền tần số.

numOfdmSymbols = size(dataSymbols, 2);

assert(size(dataSymbols, 1) == length(dataIndices), ...
    'Số hàng dataSymbols phải bằng số subcarrier dữ liệu.');
assert(length(pilotPattern) == length(pilotIndices), ...
    'Số pilot phải bằng số vị trí pilot.');
assert(all(dataIndices >= 1 & dataIndices <= NFFT), ...
    'Vị trí subcarrier dữ liệu nằm ngoài khoảng FFT.');
assert(all(pilotIndices >= 1 & pilotIndices <= NFFT), ...
    'Vị trí pilot nằm ngoài khoảng FFT.');
assert(isempty(intersect(dataIndices, pilotIndices)), ...
    'Subcarrier dữ liệu và pilot không được trùng nhau.');

X = zeros(NFFT, numOfdmSymbols);
X(dataIndices, :) = dataSymbols;
X(pilotIndices, :) = repmat( ...
    pilotPattern(:), ...
    1, ...
    numOfdmSymbols);
end

